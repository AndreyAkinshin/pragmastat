"""The arguments outside the reduction's domain.

The shared ``log-function`` fixture cannot carry them: JSON has no way to write a negative infinity
or a NaN, so the generated suite holds only the positive finite range and these are covered here or
nowhere.

These are the cases IEEE 754 leaves a platform no freedom about, so agreeing on them is not a
choice this toolkit makes; it is what makes the replacement a logarithm at all.
"""

import math
import struct

from binary64 import assert_identical

from pragmastat.log_function import log_function


def test_log_function_outside_the_reduction_domain():
    assert_identical(log_function(0.0), -math.inf, "log_function(+0)")
    assert_identical(log_function(-0.0), -math.inf, "log_function(-0)")
    assert math.isnan(log_function(-1.0))
    assert math.isnan(log_function(math.nan))
    assert_identical(log_function(math.inf), math.inf, "log_function(+inf)")
    # Exactly +0, not -0: ratio exponentiates this result, and the two zeros are distinct doubles
    # that the payload comparison in every other suite would tell apart.
    assert_identical(log_function(1.0), 0.0, "log_function(1)")


def test_log_function_is_within_one_ulp_of_the_true_logarithm():
    """The one check in this repository that does not compare the toolkit to itself.

    Every other test on this function compares seven ports against a fixture, and that fixture is
    generated by one of them. A reduction that is wrong in the same way everywhere satisfies all of
    it: the seven agree, the platform comparison in the Rust suite allows a last-bit difference,
    and nothing states what the answer should have been.

    ``decimal`` at 60 digits is an oracle outside that loop. It is exact enough that the correctly
    rounded binary64 result is determined, so this asserts accuracy rather than agreement.

    Measured over the grid below: worst error 0.7437 ulp at x = 1.6063, and 756 of 800 results
    correctly rounded. Both numbers belong to this grid and no other. The fixture's arguments
    give 0.6332 ulp and 98.22%, which is a different question about a different set of points, and
    carrying one number over to the other is how a threshold stops describing what it guards.

    The bound is one ulp because the implementation is claimed to be faithful, not correctly
    rounded. A regression in the polynomial or in the assembly moves the worst case well past it.
    """
    from decimal import Decimal, getcontext

    getcontext().prec = 60

    def ulp_of(v: float) -> float:
        packed = struct.unpack("<Q", struct.pack("<d", abs(v)))[0]
        return struct.unpack("<d", struct.pack("<Q", packed + 1))[0] - abs(v)

    xs = [1.3**e for e in range(-200, 201)]
    xs += [0.5 + 0.0037 * i for i in range(400)]
    xs = [x for x in xs if x > 0 and math.isfinite(x) and x != 1.0]

    worst, worst_at, correctly_rounded = 0.0, None, 0
    for x in xs:
        got = log_function(x)
        if got == 0.0:
            continue
        error = abs(Decimal(got) - Decimal(x).ln()) / Decimal(ulp_of(got))
        if error <= Decimal("0.5"):
            correctly_rounded += 1
        if float(error) > worst:
            worst, worst_at = float(error), x

    assert worst < 1.0, f"log_function({worst_at}) is {worst:.4f} ulp from the true logarithm"
    assert correctly_rounded / len(xs) > 0.90, f"only {correctly_rounded}/{len(xs)} results are correctly rounded"
