#!/usr/bin/env python3
"""Assert the log-function and exp-function fixtures hold the true values, not self-consistent ones.

Everything else about these two functions checks agreement. The seven ports are compared against
tests/log-function and tests/exp-function, argument by argument, on binary64 payloads. But those
fixtures are generated by one of the seven, so the whole arrangement is a closed loop: a reduction
that is wrong in the same way in every port satisfies all of it, the ports agree, the suite is
green, and nothing has said what the answer should have been.

Both functions sit on the ratio path, which is exp(median(log x - log y)), so both deserve the
same treatment. They are checked together because the check is the same one twice.

The Rust suite compares against the platform logarithm, which is a witness but not a verdict: IEEE
754 leaves the logarithm free, so a conforming platform is allowed to differ in the last bit, and
the assertion there is only that the disagreement is that small. A shared error inside that margin
passes.

`decimal` at 60 digits is outside the loop. It is far more precise than binary64, so the correctly
rounded result is determined, and comparing against it states accuracy rather than agreement. This
is what makes the fixture an oracle instead of a transcript, and through it the seven ports are
right rather than merely identical.

The bound is one ulp because the implementation is claimed to be faithful, not correctly rounded:
a range reduction plus a Chebyshev fit lands within an ulp everywhere and on the correctly rounded
value most of the time. The share is asserted too, because a regression that pushed every result
to just under one ulp would satisfy the bound alone.
"""

import json
import math
import struct
import sys
from decimal import Decimal, getcontext
from pathlib import Path

getcontext().prec = 60

# One entry per suite: the reference to compare against, how many files and comparisons the
# generator emits today, and the floor on correctly rounded results.
#
# The counts are pinned because a loader that finds nothing compares nothing and reports success:
# the failure this guard exists to prevent looks exactly like having no work to do.
#
# Both floors are measured, not chosen: the logarithm reaches 98.22% correctly rounded with a worst
# case of 0.6332 ulp, the exponential 90.77% with 0.7300. They differ because the exponential's
# assembly carries more roundings, not because one is held to a looser standard, and each floor
# sits below its own measurement with room for variation and well above nothing.
SUITES = {
    "log-function": {
        "function": "log_function",
        "reference": lambda x: Decimal(x).ln(),
        "files": 5,
        "comparisons": 1742,
        "min_correctly_rounded": 0.95,
    },
    "exp-function": {
        "function": "exp_function",
        "reference": lambda x: Decimal(x).exp(),
        "files": 4,
        "comparisons": 1029,
        "min_correctly_rounded": 0.85,
    },
}

MAX_ULP = 1.0


def ulp_of(value: float) -> float:
    """The distance to the next representable double above |value|."""
    packed = struct.unpack("<Q", struct.pack("<d", abs(value)))[0]
    return struct.unpack("<d", struct.pack("<Q", packed + 1))[0] - abs(value)


def check(root: Path, suite: str, config: dict) -> tuple[list[str], str]:
    """Compare one suite's outputs against the reference, returning failures and a summary."""
    directory = root / "tests" / suite

    files = sorted(directory.glob("*.json"))
    if len(files) != config["files"]:
        return [f"  {suite}: read {len(files)} fixture files, expected {config['files']}"], ""

    worst_ulp, worst_at, worst_file = 0.0, None, None
    correctly_rounded = 0
    compared = 0
    failures = []

    for path in files:
        case = json.loads(path.read_text())
        if case["input"]["name"] != config["function"]:
            return [f"  {path.name} names the function {case['input']['name']!r}"], ""

        for argument, output in zip(case["input"]["arg"], case["output"]):
            x, produced = float(argument), float(output)
            if not math.isfinite(x) or not math.isfinite(produced):
                continue
            # An exact zero has no meaningful ulp-relative error and is not in doubt: log(1) is 0,
            # and exp underflows to 0 below its cutoff. The ports assert both payloads themselves.
            if produced == 0.0:
                continue
            step = ulp_of(produced)
            if step == 0.0:
                continue

            error = abs(Decimal(produced) - config["reference"](Decimal(x))) / Decimal(step)
            compared += 1
            if error <= Decimal("0.5"):
                correctly_rounded += 1
            if float(error) > worst_ulp:
                worst_ulp, worst_at, worst_file = float(error), x, path.name
            if float(error) > MAX_ULP:
                failures.append(
                    f"  {suite}/{path.name}: {config['function']}({x!r}) is {float(error):.4f} ulp "
                    f"from the true value"
                )

    if compared != config["comparisons"]:
        return [
            f"  {suite}: compared {compared} outputs, expected {config['comparisons']}",
            "    re-measure and update the pin if the fixture legitimately grew",
        ], ""

    share = correctly_rounded / compared
    if share < config["min_correctly_rounded"]:
        failures.append(
            f"  {suite}: only {correctly_rounded} of {compared} outputs ({100 * share:.2f}%) are "
            f"correctly rounded, the floor is {100 * config['min_correctly_rounded']:.0f}%"
        )

    summary = (
        f"{compared} {suite} outputs are within {MAX_ULP} ulp of a 60-digit reference "
        f"({100 * share:.2f}% correctly rounded, worst {worst_ulp:.4f} ulp at {worst_at!r} "
        f"in {worst_file})"
    )
    return failures, summary


def main() -> int:
    root = Path(sys.argv[1] if len(sys.argv) > 1 else ".").resolve()

    failures, summaries = [], []
    for suite, config in SUITES.items():
        suite_failures, summary = check(root, suite, config)
        failures += suite_failures
        if summary:
            summaries.append(summary)

    if failures:
        print("ERROR: a generated fixture does not hold the true value:", file=sys.stderr)
        print("\n".join(failures[:20]), file=sys.stderr)
        if len(failures) > 20:
            print(f"  ... and {len(failures) - 20} more", file=sys.stderr)
        return 1

    for summary in summaries:
        print(summary)
    return 0


if __name__ == "__main__":
    sys.exit(main())
