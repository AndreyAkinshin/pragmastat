#!/usr/bin/env python3
"""Assert that a constant carried by more than one port carries the same binary64 in each.

tests/check_coefficients.py already pins the Horner chains against the fit scripts that produce
them. It does not see the standalone literals around those chains: the two halves of ln 2, the
band edge sqrt(2)/2, the subnormal prescaling, the normalizing constant of the normal density, the
smallest positive subnormal. Those are transcribed by hand into seven files apiece and nothing
compared them. A one-digit slip in one port would survive every suite that port shares, because
the fixtures are generated by C# and the drift gates compare a port against the fixture rather
than against its six siblings.

Comparison is by payload, not by text, because the ports spell the same double differently: Rust
writes 0.6931471803691238 where the other six write 6.9314718036912382e-01, and both parse to
0x3FE62E42FEE00000.

Names are normalized across casing conventions, so LN2_HI, ln2Hi and Ln2Hi are one constant. That
normalization is deliberately not an alias table: two ports that spell a constant differently are
made to spell it the same, because a table of accepted spellings is a place to record the drift
instead of removing it, and it grows one entry per port that gets it wrong.

The counts at the bottom are pinned for the reason every count in this repository is pinned: a
parser that stops recognizing one language's syntax finds fewer constants and reports success over
a smaller set. That already happened three times: a regex requiring an alphabetic type annotation
skipped every Rust `: f64`, one requiring the declaration to start the line skipped Go's grouped
const blocks, and one anchoring the literal without a suffix skipped R's `512L`. The count could
not expose the third, because it was pinned while the gap was already open. A pin records what is
currently visible; it does not certify that everything is.
"""

import re
import struct
import sys
from collections import defaultdict
from pathlib import Path

# Where each port keeps code, and which extension to walk. Test sources are excluded: a test may
# legitimately restate a constant to compare against, and one already does.
PORTS = {
    "rs": ("rs/pragmastat/src", ".rs"),
    "go": ("go", ".go"),
    "py": ("py/pragmastat", ".py"),
    "ts": ("ts/src", ".ts"),
    "cs": ("cs/Pragmastat", ".cs"),
    "kt": ("kt/src/main/kotlin/dev/pragmastat", ".kt"),
    "r": ("r/pragmastat/R", ".R"),
}

# One declaration per line, in any of the seven syntaxes:
#   pub(crate) const LN2_HI: f64 = 0.69...;      internal const double Ln2Hi = 6.9...e-01;
#   ln2Hi  = 6.9...e-01     (inside a Go const block)
#   _LN2_HI = 6.9...e-01                         private const val LN2_HI = 6.9...e-01
#   export const LN2_HI = 6.9...e-1;             .LN2_HI <- 6.9...e-01
#
# Modifiers repeat (Kotlin writes `const val`, C# writes `const double`), the type annotation is
# optional and may contain digits, and Go states constness once for a whole parenthesized block
# rather than on each line.
MODIFIER = (
    r"(?:pub(?:\([a-z]+\))?|export|public|private|internal|protected"
    r"|const|let|val|var|readonly|static|final"
    # Type names appear where a language puts the type before the identifier. Integer
    # types belong here too: a threshold like MaxExactSize is a shared constant, and
    # leaving them out made this checker skip every C# `const int` in silence.
    r"|double|float|number|f64|f32|Double|Float"
    r"|int|long|short|byte|uint|ulong|usize|isize|i8|i16|i32|i64|u8|u16|u32|u64"
    r"|Int|Long|Short|Byte|integer)"
)
DECLARATION = re.compile(
    r"^\s*(?:" + MODIFIER + r"\s+)*"
    r"[._]?([A-Za-z][A-Za-z0-9_]*)\s*"
    r"(?::\s*[A-Za-z][A-Za-z0-9_]*\s*)?"
    r"(?:=|<-)\s*"
    # The suffix is matched outside the capture, so what is captured still parses as a float.
    # Without it `.SIGN_MARGIN_SCALE_STEP <- 512L` was not collected at all, and R's integer
    # literals are written that way throughout: the line did not fail to compare, it failed to
    # exist, and the pinned totals below were set while it did not, so nothing could report it.
    # Kotlin's `L` and C#'s `f` are the same shape in the other ports.
    r"(-?(?:\d+\.\d*|\.\d+|\d+)(?:[eE][+-]?\d+)?)[LlFf]?\s*[;,]?\s*(?://.*)?$"
)

# Marks a line as declaring a constant rather than assigning a local.
CONSTNESS = re.compile(r"\b(?:const|val|readonly|static|final)\b")
GO_CONST_BLOCK_OPEN = re.compile(r"^\s*const\s*\($")
SCREAMING = re.compile(r"^[._]?[A-Z][A-Z0-9_]*$")

COMMENT_STARTS = ("//", "#", "*", "/*", "'")

# A constant has to appear in at least this many ports before disagreement is meaningful. Below it
# the name is probably a local of the same spelling rather than a shared constant.
SHARED_THRESHOLD = 2

# Counts, pinned. Raise them deliberately when a constant is added to the toolkit.
#
# Declarations are counted per port rather than summed. The failure this number exists to catch is
# one language's syntax falling out of the regex, and that is a per-port event: as a single total
# it is canceled by any port that gained a constant in the same commit, and the run stays green
# while a whole language has gone unread. The shared count stays one number because a shared
# constant is by definition not attributable to one port.
EXPECTED_SHARED = 24
EXPECTED_DECLARATIONS = {"cs": 22, "go": 19, "kt": 19, "py": 18, "r": 11, "rs": 19, "ts": 19}


def payload(value):
    """The binary64 bits of a float, which is what 'the same constant' has to mean here."""
    return struct.unpack("<Q", struct.pack("<d", value))[0]


def normalize(name):
    """LN2_HI, ln2Hi, Ln2Hi and _LN2_HI are one constant."""
    return re.sub(r"[^a-z0-9]", "", name.lower())


def identity(module, name):
    """What makes two declarations the same constant: the module they sit in, and the name.

    The name alone is not enough, and the failure is not hypothetical. `MaxExactSize` is 63 inside
    SignedRankMargin and 400 inside PairwiseMargin, and a name-only key reported those two as one
    constant with two payloads. That is a false finding, and a false finding on a guard is worse
    than a missing one: it teaches the reader to explain the output away.

    The module is the file, normalized the same way the name is, so SignedRankMargin.cs,
    SignedRankMargin.kt, signed_rank_margin.rs and signedRankMargin.ts are one module.

    A port with no nesting spells the distinction into the name instead: Go writes
    `signedRankMaxExactSize`, TypeScript `SIGNED_RANK_MAX_EXACT_SIZE`, where C# relies on the
    class. Stripping a module-name prefix off the constant makes those the same key rather than
    two, which is what lets the comparison cross that difference instead of being defeated by it.
    """
    module = normalize(module)
    name = normalize(name)
    if name.startswith(module) and len(name) > len(module):
        name = name[len(module):]
    else:
        # Modules are named after what they compute, so the constant often carries only the
        # leading word: signedRankMargin -> signedRank.
        for cut in range(len(module) - 1, 3, -1):
            if name.startswith(module[:cut]) and len(name) > cut:
                name = name[cut:]
                break
    return module, name


def collect(repo_root):
    """Every float constant declared by every port, keyed by normalized name."""
    found = defaultdict(lambda: defaultdict(set))
    declarations = defaultdict(int)
    for lang, (relative, extension) in PORTS.items():
        root = repo_root / relative
        if not root.is_dir():
            raise SystemExit(f"ERROR: {root} does not exist; the port layout moved.")
        for path in sorted(root.rglob("*" + extension)):
            if re.search(r"test", str(path), re.IGNORECASE):
                continue
            in_go_const_block = False
            for line in path.read_text().splitlines():
                stripped = line.strip()
                if lang == "go":
                    if GO_CONST_BLOCK_OPEN.match(stripped):
                        in_go_const_block = True
                        continue
                    if in_go_const_block and stripped == ")":
                        in_go_const_block = False
                        continue
                if stripped.startswith(COMMENT_STARTS):
                    continue
                match = DECLARATION.match(stripped)
                if not match:
                    continue
                name, literal = match.group(1), match.group(2)
                # Integers are kept. A shared threshold, a scaling exponent or a hash seed is as
                # much a constant as a fitted coefficient, and the sign margin's scale step and the
                # FNV pair are
                # exactly the kind that would go unnoticed if one port drifted. The constness
                # test below is what keeps loop bounds and indices out.
                #
                # A constant either says so with a keyword, sits in a Go const block, or is
                # spelled in the screaming case Python and R use for one. Anything else is a
                # local that happens to hold a float.
                declared_const = CONSTNESS.search(stripped) or in_go_const_block or SCREAMING.match(name)
                if not declared_const or len(name) < 4:
                    continue
                found[identity(path.stem, name)][lang].add(float(literal))
                declarations[lang] += 1
    return found, declarations


def main(repo_root="."):
    root = Path(repo_root)
    found, declarations = collect(root)
    shared = {k: v for k, v in found.items() if len(v) >= SHARED_THRESHOLD}

    failures = []
    for name in sorted(shared):
        values = set()
        for per_lang in shared[name].values():
            values |= per_lang
        payloads = {payload(v) for v in values}
        if len(payloads) != 1:
            detail = ", ".join(f"{lang}={sorted(vals)}" for lang, vals in sorted(shared[name].items()))
            module, constant = name
            failures.append(f"  {module}.{constant}: {len(payloads)} distinct payloads -> {detail}")

    if failures:
        print("ERROR: a constant carried by several ports does not agree with itself:", file=sys.stderr)
        print("\n".join(failures), file=sys.stderr)
        print("\nThe ports may spell a double differently, but it has to parse to the same bits.", file=sys.stderr)
        return 1

    drift = [
        f"  {lang}: read {declarations[lang]} declarations, expected {EXPECTED_DECLARATIONS[lang]}"
        for lang in sorted(PORTS)
        if declarations[lang] != EXPECTED_DECLARATIONS[lang]
    ]
    if len(shared) != EXPECTED_SHARED:
        drift.append(f"  shared: {len(shared)} constants carried by two or more ports, expected {EXPECTED_SHARED}")
    if drift:
        print("ERROR: the scan is not the size this file records:", file=sys.stderr)
        print("\n".join(drift), file=sys.stderr)
        print(
            "\nA parser that stops recognizing one language's syntax compares fewer constants and\n"
            "reports success over a smaller set, which is the failure this count exists to make\n"
            "visible. Counted per port, because as one total a language falling out of the regex is\n"
            "canceled by any port that gained a constant in the same commit. Update the counts in\n"
            "this file if the change was deliberate.",
            file=sys.stderr,
        )
        return 1

    total = sum(declarations.values())
    print(f"{len(shared)} shared constants agree across the ports that carry them ({total} declarations read)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1] if len(sys.argv) > 1 else "."))
